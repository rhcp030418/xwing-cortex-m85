/* ================================================================
 * ex1: 배열 합 — 네 첫 ARM 어셈블리 커널
 *
 * C 시그니처:  uint32_t asm_sum(const uint32_t *arr, uint32_t n);
 *
 * 호출 규약(AAPCS) 최소 지식:
 *   - 첫째 인자 → r0, 둘째 인자 → r1
 *   - 반환값 → r0에 넣고 bx lr로 복귀
 *   - r0~r3, r12는 마음대로 써도 됨(caller-saved)
 *   - r4~r11을 쓰려면 push/pop으로 보존해야 함 (여기선 안 씀)
 * ================================================================ */
    .syntax unified
    .cpu cortex-m4
    .thumb

    .text
    .global asm_sum
    .thumb_func
asm_sum:
    movs  r2, #0            /* r2 = 누적합 = 0 */
loop:
    cbz   r1, done          /* r1(남은 개수)이 0이면 done으로 (compare-and-branch-if-zero) */
    ldr   r3, [r0], #4      /* r3 = 메모리[r0] 읽고, r0 += 4  (포스트 증가 로드) */
    add   r2, r2, r3        /* 합 += r3 */
    subs  r1, r1, #1        /* 남은 개수 -1 */
    b     loop
done:
    mov   r0, r2            /* 반환값은 r0에 */
    bx    lr

/* ----------------------------------------------------------------
 * [과제] 위 루프는 원소 1개당 명령 5개(cbz/ldr/add/subs/b)를 쓴다.
 *
 * 1. subs가 만든 플래그를 이용해 cbz 없이 4개로 줄여봐라.
 *    힌트: 루프 구조를 "몸통 → subs → bne loop"로 바꾸면 된다.
 *    (n=0 케이스는 진입 전에 한 번만 검사)
 *
 * 2. 원소 2개씩 처리(언롤링)해봐라. 힌트: ldrd r3, r4, [r0], #8
 *    (r4를 쓰면 push {r4} / pop {r4} 잊지 말 것!)
 *
 * 3. 생각해보기: M4(싱글이슈)에서는 명령 수 = 대략 사이클 수다.
 *    M85(듀얼이슈)에서는 왜 그 등식이 깨질까? 어떤 명령끼리
 *    같은 사이클에 나란히 탈 수 있을까? ← 우리 연구의 출발점
 * ---------------------------------------------------------------- */
